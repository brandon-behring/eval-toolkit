#!/usr/bin/env python
"""Per-module coverage floor enforcement.

coverage.py only ships a global ``fail_under``; this script adds the
per-module floor that issue #37 requires. Reads ``coverage.json``
(generated by ``pytest --cov-report=json``) and asserts each
``src/eval_toolkit/*.py`` module clears the floor.

Default floor: 85%. Two override mechanisms for optional-deps modules:

- ``# pragma: no cover`` on optional-active paths (``seeds.py``,
  ``embeddings.py`` — they sit at 100% in CI via this route).
- ``FLOORS`` per-module overrides (below) for modules whose test suites
  skip wholesale on the documented dev install (issue #102).

Runs in CI on the ubuntu job (per-module percentages can drift across
OSes via platform-conditional branches) and locally via ``make coverage``.

Exit code: 0 on pass, 1 on floor violation, 2 on missing input.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

# Per-module floor overrides. Keys are paths as recorded in coverage.json
# (typically ``src/eval_toolkit/<module>.py``). Default floor applies
# when a module is not listed here.
FLOORS: dict[str, float] = {
    # Dev-install reality (issue #102): [dev] -> [all] deliberately excludes the
    # torch-pulling extras (probes/losses/embeddings/transformers) and there is no
    # extra for HF `datasets`, so these modules' tests skip on the documented install
    # AND in CI. Floor = just below observed dev-install coverage: the gate enforces
    # "no regression below documented-install reality", not aspiration. Revisit if a
    # nightly heavy-extras coverage job is added.
    # Observed 2026-06-11 (fresh `uv sync --extra dev --extra docs` env):
    "src/eval_toolkit/losses.py": 18.0,  # observed 20.3%
    "src/eval_toolkit/probes.py": 75.0,  # observed 78.2%
    "src/eval_toolkit/loaders.py": 78.0,  # observed 80.6%
}
DEFAULT_FLOOR = 85.0


def main() -> int:
    cov_json = Path("coverage.json")
    if not cov_json.exists():
        print(
            "ERROR: coverage.json not found. Run pytest with " "--cov-report=json first.",
            file=sys.stderr,
        )
        return 2

    data = json.loads(cov_json.read_text(encoding="utf-8"))
    failures: list[tuple[str, float, float]] = []

    for fname, summary in data["files"].items():
        pct = summary["summary"]["percent_covered"]
        floor = FLOORS.get(fname, DEFAULT_FLOOR)
        if pct < floor:
            failures.append((fname, pct, floor))

    if failures:
        print(f"FAIL: {len(failures)} module(s) below floor:")
        for fname, pct, floor in failures:
            print(f"  {fname}: {pct:.1f}% < {floor:.1f}%")
        return 1

    if FLOORS:
        overrides = ", ".join(
            f"{Path(fname).name} >= {floor:.0f}%" for fname, floor in sorted(FLOORS.items())
        )
        print(
            f"OK: all modules >= {DEFAULT_FLOOR:.0f}% "
            f"({len(FLOORS)} documented dev-install overrides: {overrides})"
        )
    else:
        print(f"OK: all modules >= {DEFAULT_FLOOR:.0f}%")
    return 0


if __name__ == "__main__":
    sys.exit(main())
